// Package sqlbundle combines the migrations and seed into one SQL file, for
// setting up a database from the Supabase SQL editor without any tools.
package sqlbundle

import (
	"fmt"
	"io/fs"
	"sort"
	"strconv"
	"strings"

	"dfipam/api/internal/seed"
	"dfipam/api/migrations"
)

func Build() (string, error) {
	names, err := fs.Glob(migrations.FS, "*.up.sql")
	if err != nil {
		return "", err
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("-- DF-IPAM full database setup. Generated by `make sql`: do not edit.\n")
	b.WriteString("-- Runs as one transaction on an empty database, and records the migration\n")
	b.WriteString("-- version so `make migrate-up` continues from here.\n\nBEGIN;\n\n")
	b.WriteString("CREATE TABLE schema_migrations (version bigint NOT NULL PRIMARY KEY, dirty boolean NOT NULL);\n\n")
	latest := 0
	for _, name := range names {
		body, err := migrations.FS.ReadFile(name)
		if err != nil {
			return "", err
		}
		if latest, err = strconv.Atoi(strings.SplitN(name, "_", 2)[0]); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "-- %s\n%s\n", name, body)
	}
	fmt.Fprintf(&b, "-- Seed data\n%s\nINSERT INTO schema_migrations (version, dirty) VALUES (%d, false);\n\nCOMMIT;\n", seed.SQL(), latest)
	return b.String(), nil
}
